const { createRequire } = require("node:module");
const { existsSync, mkdirSync, writeFileSync } = require("node:fs");
const { resolve, join } = require("node:path");
const { tmpdir } = require("node:os");
const { spawn } = require("node:child_process");
const assert = require("node:assert/strict");
const puppeteer = createRequire(resolve(".vencord/package.json"))("puppeteer-core");

(async () => {
  const executablePath = [process.env.EDGE_BIN, "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", "C:/Program Files/Microsoft/Edge/Application/msedge.exe"].find((path) => path && existsSync(path));
  const server = spawn(resolve("src-tauri/target/debug/examples/soundboard_server" + (process.platform === "win32" ? ".exe" : "")), [], { stdio: ["ignore", "pipe", "inherit"] });
  let browser;
  try {
    const url = await new Promise((resolve, reject) => {
      let text = "";
      const timer = setTimeout(() => reject(new Error("Le serveur de test n'a pas démarré.")), 15000);
      server.on("error", (error) => { clearTimeout(timer); reject(error); });
      server.stdout.on("data", (chunk) => { text += chunk; if (text.includes("\n")) { clearTimeout(timer); try { resolve(JSON.parse(text.split("\n")[0]).url); } catch (error) { reject(error); } } });
    });
    browser = await puppeteer.launch({ executablePath, headless: true, args: ["--no-sandbox"] });
    const pc = await browser.newPage();
    const errors = []; pc.on("pageerror", (error) => errors.push(error.message));
    await pc.setViewport({ width: 1360, height: 920 });
    await pc.goto(url);
    await pc.waitForSelector("#grid .card");
    assert.equal(await pc.$$eval("#grid .card", (cards) => cards.length), 12);
    assert.equal(await pc.evaluate(() => location.hash), "");
    await pc.click('button[aria-label="Jouer Airhorn"]');
    await pc.waitForFunction(() => document.querySelector("#feedback").textContent.includes("fixture-0"));
    await pc.type("#search", "suspense");
    assert.equal(await pc.$$eval("#grid .card", (cards) => cards.length), 1);
    await pc.$eval("#search", (input) => { input.value = ""; input.dispatchEvent(new Event("input")); });
    await pc.click('[data-filter="favorites"]');
    assert.equal(await pc.$$eval("#grid .card", (cards) => cards.length), 3);
    await pc.click('[data-filter="all"]');
    await pc.click('button[aria-label="Modifier Airhorn"]');
    await pc.$eval("#edit-name", (input) => { input.value = "Airhorn test"; });
    await pc.click("#save");
    await pc.waitForSelector('button[aria-label="Jouer Airhorn test"]');
    const file = join(tmpdir(), "test.wav"); writeFileSync(file, "RIFFtest");
    await (await pc.$("#file")).uploadFile(file);
    await pc.waitForSelector('button[aria-label="Jouer test.wav"]');
    await pc.click("#remote-button");
    await pc.click("#remote-toggle");
    await pc.waitForSelector("#qr svg");
    const link = await pc.$eval("#pair-link", (node) => node.textContent);
    const mobileUrl = new URL(link); mobileUrl.hostname = "127.0.0.1";
    const phoneContext = await browser.createBrowserContext();
    const phone = await phoneContext.newPage();
    phone.on("pageerror", (error) => errors.push(error.message));
    await phone.setViewport({ width: 390, height: 844, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
    await phone.goto(mobileUrl.href);
    await phone.waitForSelector("#grid .card");
    assert.equal(await phone.$eval("#remote-button", (node) => node.hidden), true);
    await phone.tap('button[aria-label="Jouer Victoire"]');
    await pc.waitForFunction(() => document.querySelector("#feedback").textContent.includes("fixture-3"));
    await phone.$eval("#volume", (input) => { input.value = "35"; input.dispatchEvent(new Event("change")); });
    await pc.waitForFunction(() => document.querySelector("#volume").value === "35");
    await phone.tap("#stop");
    await pc.waitForFunction(() => document.querySelector("#feedback").textContent.includes("Sons arrêtés"));
    mkdirSync("tests-output", { recursive: true });
    await pc.click('[data-close="remote"]');
    await pc.screenshot({ path: "tests-output/soundboard-desktop.png" });
    await phone.screenshot({ path: "tests-output/soundboard-phone.png" });
    await pc.click("#remote-button");
    await pc.screenshot({ path: "tests-output/soundboard-pairing.png" });
    await pc.click("#remote-toggle");
    await phone.waitForFunction(() => !document.querySelector("#pair").classList.contains("hidden"));
    assert.deepEqual(errors, [], "Erreurs JavaScript du contrôleur");
    console.log("Soundboard : HTTP natif, import PC, favoris, recherche, appairage, lecture mobile, volume, arrêt et révocation validés.");
  } finally { if (browser) await browser.close(); server.kill(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
